def _stem(site: str) -> str:
    return urlsplit(site).netloc.replace("www.", "").replace(":", "_")


def result_dict(r: AuditResult) -> dict:
    return {
        "site": r.site, "audited_at": r.audited_at, "error": r.error,
        "platform": r.platform.name, "theme": r.platform.theme, "apps": r.platform.apps,
        "third_party_hosts": len(r.platform.third_party_hosts),
        "pages_audited": len(r.pages), "links_checked": r.links_checked, "sitemap_urls": r.sitemap_count,
        "requests": r.requests, "seconds": r.seconds, "scores": r.scores, "counts": r.counts,
        "findings": [f.to_dict() for f in r.findings],
    }


def write_reports(r: AuditResult, out_dir: str | Path, prepared_by: str = "") -> dict[str, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    stem = _stem(r.site)
    files = {"json": out / f"{stem}.json", "csv": out / f"{stem}_issues.csv", "html": out / f"{stem}.html"}
    files["json"].write_text(json.dumps(result_dict(r), indent=2), encoding="utf-8")
    with open(files["csv"], "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["severity", "category", "check", "title", "affected", "evidence"])
        for f in r.findings:
            writer.writerow([f.severity, f.category, f.check, f.title, f.affected, " | ".join(f.evidence)])
    if not r.error:
        kinds = ", ".join(f"{n} {k}" for k, n in Counter(p.kind for p in r.pages).items())
        html = Environment(autoescape=True).from_string(TEMPLATE).render(
            r=r, host=urlsplit(r.site).netloc, kinds=kinds, prepared_by=prepared_by)
        files["html"].write_text(html, encoding="utf-8")
    else:
        files.pop("html")
    return files


def write_portfolio(results: list[AuditResult], out_dir: str | Path) -> Path:
    out = Path(out_dir)
    ok = [r for r in results if not r.error]
    lines = ["# Portfolio audit summary", "",
             f"{len(ok)} of {len(results)} sites audited, {sum(len(r.pages) for r in ok)} pages, "
             f"{sum(r.links_checked for r in ok)} links checked, {sum(r.requests for r in ok)} requests.", "",
             "| Site | Platform | Overall | Critical | High | Medium | Pages |", "|---|---|---|---|---|---|---|"]
    for r in sorted(ok, key=lambda r: r.scores.get("overall", 0)):
        c = r.counts
        lines.append(f"| {urlsplit(r.site).netloc} | {r.platform.name} | {r.scores['overall']} | {c['critical']} | {c['high']} | {c['medium']} | {len(r.pages)} |")
    for r in results:
        if r.error:
            lines.append(f"| {urlsplit(r.site).netloc} | not audited: {r.error} | | | | | |")
    common = Counter(f.title for r in ok for f in r.findings)
    lines += ["", "## Most common findings", "", "| Finding | Sites |", "|---|---|"]
    lines += [f"| {title} | {n} |" for title, n in common.most_common(12)]
    path = out / "PORTFOLIO.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
